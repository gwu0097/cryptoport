// Regenerates src/lib/adapters/cosmosChainNames.ts: display names for every
// Cosmos chain the Cosmos multi-chain wallet can scan (live mainnet, coin
// type 118, per cosmos.directory). Chain names rarely change; a chain added
// after the last run just shows its slug until this is re-run.
//
//   node scripts/gen-cosmos-chain-names.mjs
import { writeFileSync } from "node:fs";

const res = await fetch("https://chains.cosmos.directory/");
if (!res.ok) throw new Error(`cosmos.directory failed: HTTP ${res.status}`);
const chains = (await res.json()).chains
  .filter((c) => c.slip44 === 118 && c.status === "live" && c.network_type === "mainnet" && c.name && c.pretty_name)
  .sort((a, b) => a.name.localeCompare(b.name));
const body = chains.map((c) => `  ${JSON.stringify(c.name)}: ${JSON.stringify(c.pretty_name)},`).join("\n");
writeFileSync(
  new URL("../src/lib/adapters/cosmosChainNames.ts", import.meta.url),
  `// GENERATED by scripts/gen-cosmos-chain-names.mjs from cosmos.directory — do
// not edit by hand. Display names for the Cosmos chains the Cosmos
// multi-chain wallet scans (holding.chain = the cosmos.directory chain name).
export const COSMOS_CHAIN_NAMES: Record<string, string> = {
${body}
};
`,
);
console.log(`wrote ${chains.length} Cosmos chain names`);
